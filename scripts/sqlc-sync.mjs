#!/usr/bin/env node
// Regenerates apps/api/sqlc.yaml from the module list and the per-module
// baseline migrations (F8-15/F8-18): one block per module that owns tables,
// `schema` = ONLY that module's migration files, so a query that names another
// module's table fails at `sqlc generate` time (the compiler enforces the
// boundary, not just arch-check Rule T).
//
// Usage: node scripts/sqlc-sync.mjs           rewrite apps/api/sqlc.yaml
//        node scripts/sqlc-sync.mjs --check   exit 1 when the file is stale
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const API = join(ROOT, "apps/api");

export function renderSqlcYaml(api = API) {
  const modulesDir = join(api, "internal/modules");
  const modules = readdirSync(modulesDir).filter((m) => statSync(join(modulesDir, m)).isDirectory()).sort();
  const migs = readdirSync(join(api, "migrations")).filter((f) => f.endsWith(".up.sql")).sort();
  const byModule = new Map();
  for (const f of migs) {
    const m = /^\d+_([a-z0-9]+)/.exec(f)?.[1];
    if (!m) continue;
    if (!byModule.has(m)) byModule.set(m, []);
    byModule.get(m).push(f);
  }
  let out = `# GENERATED by scripts/sqlc-sync.mjs — do not edit by hand (node scripts/sqlc-sync.mjs).
# One block per module that owns tables; schema = that module's own migration
# files only (a cross-module table reference fails at generate time).
# Modules without tables (reporting) have no block.
version: "2"
sql:
`;
  for (const m of modules.filter((m) => byModule.has(m))) {
    out += `  - engine: mysql
    schema:
${byModule.get(m).map((f) => `      - migrations/${f}`).join("\n")}
    queries: internal/modules/${m}/infrastructure/queries
    gen:
      go:
        package: sqlc
        out: internal/modules/${m}/infrastructure/sqlc
        emit_empty_slices: true
        overrides:
          - { db_type: bigint, unsigned: true, go_type: int64 }
          - { db_type: bigint, unsigned: true, nullable: true, go_type: database/sql.NullInt64 }
          - { db_type: decimal, go_type: float64 }
          - { db_type: decimal, nullable: true, go_type: database/sql.NullFloat64 }
`;
  }
  return out;
}

if (process.argv[1] && process.argv[1].endsWith("sqlc-sync.mjs")) {
  const want = renderSqlcYaml();
  const path = join(API, "sqlc.yaml");
  if (process.argv.includes("--check")) {
    let have = "";
    try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (have.replace(/\r\n/g, "\n") !== want) {
      process.stdout.write("sqlc-sync: apps/api/sqlc.yaml is stale — run node scripts/sqlc-sync.mjs\n");
      process.exit(1);
    }
    process.stdout.write("sqlc-sync: apps/api/sqlc.yaml up to date.\n");
  } else {
    writeFileSync(path, want);
    process.stdout.write("sqlc-sync: wrote apps/api/sqlc.yaml\n");
  }
}
