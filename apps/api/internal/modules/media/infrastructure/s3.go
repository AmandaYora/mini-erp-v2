package infrastructure

import (
	"context"
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/credentials"
	"github.com/aws/aws-sdk-go-v2/service/s3"
)

// S3Driver stores bytes in an S3-compatible bucket (legacy: IDCloudHost
// https://is3.cloudhost.id, bucket mini-erp, path-style). Files stay
// private; reads go through presigned URLs (300 dtk default, warisan).
type S3Driver struct {
	client        *s3.Client
	deleter       deleteObjectAPI
	presign       *s3.PresignClient
	bucket        string
	publicBaseURL string
	ttl           time.Duration
	// uploadPrefixes are the deployment's own key prefixes (F1-9): Remove
	// only deletes keys under one of them, so a stray or legacy key can
	// never be wiped. protectedPrefixes are never deleted (e.g. the legacy
	// production prefix during the rollback window).
	uploadPrefixes    []string
	protectedPrefixes []string
}

// deleteObjectAPI is the one S3 call Remove needs. The concrete *s3.Client
// implements it; tests substitute a fake (F1-9).
type deleteObjectAPI interface {
	DeleteObject(ctx context.Context, params *s3.DeleteObjectInput, optFns ...func(*s3.Options)) (*s3.DeleteObjectOutput, error)
}

// S3Config carries the object-storage settings (see config.Storage).
type S3Config struct {
	Endpoint        string
	Bucket          string
	Region          string
	ForcePathStyle  bool
	AccessKeyID     string
	SecretAccessKey string
	PublicBaseURL   string
	SignedURLTTLS   time.Duration
	// UploadPrefixes bounds deletes to this deployment's keys (F1-9). Empty
	// keeps the historical allow-all behavior (dev/local parity); production
	// always sets them via the module wiring below.
	UploadPrefixes []string
	// ProtectedPrefixes are never deleted even when under UploadPrefixes.
	ProtectedPrefixes []string
}

// NewS3Driver builds the bucket client. Bucket + keys are validated by the
// composition root (config.Load) before this runs.
func NewS3Driver(cfg S3Config) *S3Driver {
	client := s3.New(s3.Options{
		Region: cfg.Region,
		Credentials: aws.NewCredentialsCache(credentials.NewStaticCredentialsProvider(
			cfg.AccessKeyID, cfg.SecretAccessKey, "")),
		BaseEndpoint: aws.String(cfg.Endpoint),
		UsePathStyle: cfg.ForcePathStyle,
		DefaultsMode: aws.DefaultsModeStandard,
	})
	return &S3Driver{
		client: client, deleter: client, presign: s3.NewPresignClient(client),
		bucket: cfg.Bucket, publicBaseURL: cfg.PublicBaseURL, ttl: cfg.SignedURLTTLS,
		uploadPrefixes:    cleanKeys(cfg.UploadPrefixes),
		protectedPrefixes: cleanKeys(cfg.ProtectedPrefixes),
	}
}

// cleanKeys trims slashes/whitespace and drops empties so prefix matching
// cannot be fooled by "//" or blank entries.
func cleanKeys(in []string) []string {
	var out []string
	for _, k := range in {
		if k = strings.Trim(strings.TrimSpace(k), "/"); k != "" {
			out = append(out, k)
		}
	}
	return out
}

// underPrefix reports whether key equals prefix or lives below prefix+"/".
// A bare strings.HasPrefix would treat "vioni/prod-evil" as inside
// "vioni/prod", so the boundary slash is mandatory.
func underPrefix(key, prefix string) bool {
	return key == prefix || strings.HasPrefix(key, prefix+"/")
}

// deletable reports whether Remove may delete key (F1-9): inside the
// deployment's own prefixes and outside every protected prefix.
func (d *S3Driver) deletable(key string) bool {
	for _, p := range d.protectedPrefixes {
		if underPrefix(key, p) {
			return false
		}
	}
	if len(d.uploadPrefixes) == 0 {
		return true
	}
	for _, p := range d.uploadPrefixes {
		if underPrefix(key, p) {
			return true
		}
	}
	return false
}

// Store puts one object. Keys are always server-generated by the service.
func (d *S3Driver) Store(ctx context.Context, key string, content io.Reader, contentType, originalName string) error {
	meta := map[string]string{}
	if originalName = strings.TrimSpace(originalName); originalName != "" {
		if len(originalName) > 255 {
			originalName = originalName[:255]
		}
		meta["original_name"] = originalName
	}
	_, err := d.client.PutObject(ctx, &s3.PutObjectInput{
		Bucket: aws.String(d.bucket), Key: aws.String(key),
		Body: content, ContentType: aws.String(contentType), Metadata: meta,
	})
	return err
}

// Remove deletes one object. Missing keys are not an error (best-effort,
// same semantics as the local driver). Keys outside the deployment's own
// upload prefixes, or inside a protected prefix, are never deleted (F1-9:
// legacy objects shared with the old system survive Archive).
func (d *S3Driver) Remove(ctx context.Context, key string) {
	if !d.deletable(key) {
		return
	}
	_, _ = d.deleter.DeleteObject(ctx, &s3.DeleteObjectInput{
		Bucket: aws.String(d.bucket), Key: aws.String(key),
	})
}

// URLFor resolves a public URL when configured, else a presigned GET.
func (d *S3Driver) URLFor(ctx context.Context, key string) (string, error) {
	if d.publicBaseURL != "" {
		return d.publicBaseURL + "/" + key, nil
	}
	out, err := d.presign.PresignGetObject(ctx, &s3.GetObjectInput{
		Bucket: aws.String(d.bucket), Key: aws.String(key),
	}, s3.WithPresignExpires(d.ttl))
	if err != nil {
		return "", fmt.Errorf("gagal membuat URL berkas: %w", err)
	}
	return out.URL, nil
}
