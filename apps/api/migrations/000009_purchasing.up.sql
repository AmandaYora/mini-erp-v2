CREATE TABLE `purchase_orders` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `number` varchar(100) NOT NULL,
  `branch_id` bigint unsigned NOT NULL,
  `party_id` bigint unsigned NOT NULL,
  `order_date` datetime(6) NOT NULL,
  `due_date` datetime(6) DEFAULT NULL,
  `payment_terms` varchar(20) NOT NULL DEFAULT 'net',
  `tax_type` varchar(20) NOT NULL DEFAULT 'none',
  `tax_rate` decimal(9,4) NOT NULL DEFAULT '0.0000',
  `supplier_invoice_number` varchar(100) DEFAULT NULL,
  `supplier_invoice_date` datetime(6) DEFAULT NULL,
  `subtotal` bigint NOT NULL DEFAULT '0',
  `discount_total` bigint NOT NULL DEFAULT '0',
  `tax_total` bigint NOT NULL DEFAULT '0',
  `grand_total` bigint NOT NULL DEFAULT '0',
  `status` varchar(20) NOT NULL DEFAULT 'draft',
  `notes` text,
  `created_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `created_by` bigint unsigned DEFAULT NULL,
  `updated_by` bigint unsigned DEFAULT NULL,
  `assigned_user_id` bigint unsigned DEFAULT NULL,
  `payment_term_days` smallint unsigned DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_purchase_orders_number` (`number`),
  KEY `ix_purchase_orders_branch_id` (`branch_id`,`id`),
  KEY `ix_purchase_orders_date` (`branch_id`,`order_date`,`id`),
  KEY `ix_purchase_orders_party` (`branch_id`,`party_id`,`id`),
  KEY `ix_purchase_orders_number` (`branch_id`,`number`),
  KEY `ix_purchase_orders_status` (`branch_id`,`status`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

